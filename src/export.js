import JSZip from 'jszip'

// The preview iframe has no bundler, so: Babel (from a CDN) compiles the JSX
// in the browser, and an import map points "react"/"motion/react" at esm.sh.
// `?external=` keeps esm.sh from bundling its own React copy into motion, so
// everything shares the one React instance (two Reacts = broken hooks).
const IMPORTS = {
  react: 'https://esm.sh/react@19',
  'react/jsx-runtime': 'https://esm.sh/react@19/jsx-runtime',
  'react-dom': 'https://esm.sh/react-dom@19?external=react',
  'react-dom/client': 'https://esm.sh/react-dom@19/client?external=react',
  'motion/react': 'https://esm.sh/motion@14/react?external=react,react-dom',
}

// JSON inside <script>: escape "<" so a "</script>" in the code can't end the tag.
const embed = v => JSON.stringify(v).replace(/</g, '\\u003c')

const withAssets = (text, assets) =>
  assets.reduce((t, a) => t.split(`/assets/${a.name}`).join(a.dataUrl), text)

export function previewHtml({ app, css }, assets) {
  return `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<script type="importmap">${embed({ imports: IMPORTS })}</script>
<style>${withAssets(css, assets).replace(/<\/style/gi, '<\\/style')}</style>
<script src="https://unpkg.com/@babel/standalone@7/babel.min.js"></script>
</head><body><div id="root"></div>
<pre id="__err" style="display:none;position:fixed;inset:auto 0 0 0;max-height:40vh;overflow:auto;margin:0;padding:12px;background:#300;color:#fcc;font:12px monospace;white-space:pre-wrap;z-index:99999"></pre>
<script type="module">
const showError = msg => { const el = document.getElementById('__err'); el.style.display = 'block'; el.textContent += msg + '\\n' }
addEventListener('error', e => showError(e.message))
addEventListener('unhandledrejection', e => showError(String(e.reason?.stack || e.reason)))
try {
  let code = Babel.transform(${embed(app)}, { presets: [['react', { runtime: 'automatic' }]], filename: 'App.jsx' }).code
  const assets = ${embed(assets.map(a => [`/assets/${a.name}`, a.dataUrl]))}
  for (const [path, url] of assets) code = code.split(path).join(url)
  const url = URL.createObjectURL(new Blob([code], { type: 'text/javascript' }))
  const [{ default: App }, { createRoot }, { createElement }] = await Promise.all([import(url), import('react-dom/client'), import('react')])
  createRoot(document.getElementById('root')).render(createElement(App))
} catch (e) { showError(e.stack || e.message) }
</script></body></html>`
}

const PKG = {
  name: 'my-site',
  private: true,
  version: '0.0.0',
  type: 'module',
  scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
  dependencies: { motion: '^14.0.0', react: '^19.0.0', 'react-dom': '^19.0.0' },
  devDependencies: { '@vitejs/plugin-react': '^6.0.0', vite: '^8.0.0' },
}

export async function downloadZip({ app, css }, assets) {
  const zip = new JSZip()
  zip.file('package.json', JSON.stringify(PKG, null, 2) + '\n')
  zip.file('vite.config.js', `import { defineConfig } from 'vite'\nimport react from '@vitejs/plugin-react'\n\nexport default defineConfig({ plugins: [react()] })\n`)
  zip.file('index.html', `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n    <title>My site</title>\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.jsx"></script>\n  </body>\n</html>\n`)
  zip.file('src/main.jsx', `import { createRoot } from 'react-dom/client'\nimport App from './App.jsx'\nimport './styles.css'\n\ncreateRoot(document.getElementById('root')).render(<App />)\n`)
  zip.file('src/App.jsx', app + '\n')
  zip.file('src/styles.css', css + '\n')
  // Vite serves public/ at the site root, so /assets/x.png resolves as-is.
  for (const a of assets) zip.file(`public/assets/${a.name}`, a.dataUrl.split(',')[1], { base64: true })
  zip.file('README.md', '# My site\n\nGenerated by sketch2site.\n\n```\nnpm install\nnpm run dev\n```\n')

  const link = document.createElement('a')
  link.href = URL.createObjectURL(await zip.generateAsync({ type: 'blob' }))
  link.download = 'site.zip'
  link.click()
  setTimeout(() => URL.revokeObjectURL(link.href), 1000)
}
